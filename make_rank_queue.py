#!/usr/bin/env python3
"""make_rank_queue.py rank_models.json -> run_rank.sh (two GPU workers, resumable, smoke test first).
Models with a "gguf" entry are queued; their "files" are filled in as rank_out/<name>_<prompt>.jsonl."""
import json, re, sys, os
cfg = json.load(open(sys.argv[1]))
todo = [m for m in cfg["models"] if "gguf" in m]
bad = [m["name"] for m in todo if "FILL" in m["gguf"]]
if bad: sys.exit("gguf path still contains FILL for: " + ", ".join(bad))
for m in todo:
    slug = re.sub(r"[^A-Za-z0-9.]+", "_", m["name"])
    m["files"] = {p: f"rank_out/{slug}_{p}.jsonl" for p in cfg["prompts"]}
json.dump(cfg, open(sys.argv[1], "w"), indent=1)
todo.sort(key=lambda m: -m["params_b"])           # largest first, alternate GPUs
lines = ["#!/bin/bash", "# generated by make_rank_queue.py; safe to rerun (rerun resumes from the output files)", "mkdir -p rank_out", ""]
for g in (0, 1):
    lines.append(f"worker{g}() {{")
    for m in todo[g::2]:
        for p in cfg["prompts"]:
            out = m["files"][p]
            lines.append(f'  CUDA_VISIBLE_DEVICES={g} python3 cafa_revision.py rerun --gguf "{m["gguf"]}" --conditions 1,2 --demo {p} --out {out} >> rank_out/log_gpu{g}.txt 2>&1')
    lines += ["}", ""]
lines += ["worker0 &", "worker1 &", "wait", 'echo "ranking runs finished" | tee -a rank_out/log_done.txt']
open("run_rank.sh", "w").write("\n".join(lines) + "\n")
print(f"{len(todo)} models queued -> run_rank.sh  (smoke test each model first: see PREREG_ranking.md, step 3)")

sm = ["#!/bin/bash", "# smoke test: 20 programs x 2 conditions per model; every model must load and print plausible predictions", "mkdir -p rank_out"]
for m in todo:
    slug = re.sub(r"[^A-Za-z0-9.]+", "_", m["name"])
    sm.append(f'echo "== {m["name"]}"; CUDA_VISIBLE_DEVICES=0 python3 cafa_revision.py rerun --gguf "{m["gguf"]}" --conditions 1,2 --demo orig --limit 20 --out rank_out/smoke_{slug}.jsonl 2>&1 | tail -n 2; python3 -c "import json;r=[json.loads(l) for l in open(\'rank_out/smoke_{slug}.jsonl\')];ok=[x for x in r if x.get(\'status\')==\'ok\'];print(len(ok),\'scored of\',len(r),\'| first predictions:\',[x[\'prediction\'][:25] for x in ok[:3]])"')
open("smoke_rank.sh", "w").write("\n".join(sm) + "\n")
print("smoke test -> smoke_rank.sh")
